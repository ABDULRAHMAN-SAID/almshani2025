namespace Dawnkeep.Combat
{
    /// <summary>
    /// صنف العدوّ في قسمة الموجة (§14: «تحقق من حد أدنى وحد أقصى لكل فئة»).
    ///
    /// ليس هو `TargetClass`: ذاك **ما يقصده** العدوّ، وهذا **ما يطلبه منك**.
    /// موجة كلّها آكلي قناديل تشترك في صنف هدف واحد ومع ذلك تفرض عليك ردّاً
    /// واحداً، وهو ما تمنعه هذه القسمة.
    /// </summary>
    public enum ThreatClass
    {
        /// <summary>مشاة يُواجَهون بالخطّ الأمامي.</summary>
        Melee = 0,

        /// <summary>رماة يوجبون الخروج إليهم أو التحصّن.</summary>
        Ranged = 1,

        /// <summary>مدرَّعون بطيئون يوجبون اختراق درع أو نوراً.</summary>
        Armoured = 2,

        /// <summary>ما يقصد المنارات والاقتصاد فيسلب المنطقة.</summary>
        Saboteur = 3,

        /// <summary>سِراع خِفاف يأتون سرباً.</summary>
        Swarm = 4,

        /// <summary>زعيم أو زعيم صغير — لا يُقسَم عليه سقف الصنف.</summary>
        Boss = 5,
    }
}
