namespace Dawnkeep.Campaign
{
    /// <summary>
    /// أهداف المراحل السبعة (§19). و§19 تختم قائمتها بشرطٍ قاطع: **«لا تجعل
    /// كل الاختلافات نصًّا فقط؛ يجب أن تغير القرار الفعلي»**.
    ///
    /// فكلٌّ منها هنا يغيّر شيئاً في الساحة: عقداً تُقفَل، أو منارتين تُشترطان،
    /// أو قافلةً تُحمى، أو جداراً يبدأ مكسوراً. ومرحلةٌ تختلف بسطرٍ في
    /// وصفها وحده ليست مرحلةً ثانية.
    /// </summary>
    public enum StageObjective
    {
        /// <summary>حماية القلب فقط — الشرط الأساس (§5).</summary>
        HoldTheKeep = 0,

        /// <summary>
        /// حماية قافلة ثابتة حتى الفجر. مبنىً لا يُصلَح ولا يُباع، وسقوطُه
        /// خسارةٌ ولو صمد القلب.
        /// </summary>
        GuardConvoy = 1,

        /// <summary>
        /// تشغيل منارتين خارجيّتين. لا يتحقّق الفوز ما لم تُضاءا معاً عند
        /// آخر ليلة — فالنور صار شرطاً لا اختياراً.
        /// </summary>
        LightTwoBeacons = 2,

        /// <summary>الصمود بستّ عقد بناءٍ فقط. الباقي مقفَل طول المرحلة.</summary>
        SixNodesOnly = 3,

        /// <summary>بوّابتان: الموجة تنقسم بينهما، فيُقسَم الجيش.</summary>
        TwoGates = 4,

        /// <summary>
        /// مرحلة اقتصادية: تبدأ بلا أبراج **ولا تُبنى إلّا بعد الليلة
        /// الثالثة**. القرار: أن تعيش بالجند والبطل حتى تُفتح.
        /// </summary>
        EconomyOpening = 5,

        /// <summary>حصار: جدارٌ يبدأ مكسوراً — ثغرةٌ في السور من أوّل ليلة.</summary>
        BrokenWall = 6,
    }
}
