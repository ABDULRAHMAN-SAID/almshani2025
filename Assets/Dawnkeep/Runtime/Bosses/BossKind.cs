namespace Dawnkeep.Bosses
{
    /// <summary>
    /// رتبة الزعيم (§14: «زعيم صغير كل خمس موجات وزعيم كامل كل عشر»).
    ///
    /// بيانٌ لا اشتقاق: لولا هذا الحقل لَحُسمت الرتبة بالثمن، فيصير زعيم
    /// الحملة أغلى ما في الكتالوج فيخرج في كل ليلةٍ كاملة، ولا يُرى غيره.
    /// </summary>
    public enum BossRank
    {
        /// <summary>يخرج في ليالي الخمس.</summary>
        Mini = 0,

        /// <summary>يخرج في ليالي العشر — ومنه زعيم الحملة.</summary>
        Full = 1,
    }

    /// <summary>زعماء §13 الأربعة. الترتيب هو ترتيب ظهورهم في الحملة.</summary>
    public enum BossKind
    {
        /// <summary>كبش الجرس: يندفع بخطٍّ مستقيم بعد إنذار، ويُصعق في النور.</summary>
        BellRam = 0,

        /// <summary>أمّ المستنقع: برك سمّ وبيضٌ يُفقس، وتَسِم بيتين أو مزرعتين.</summary>
        MireMatron = 1,

        /// <summary>تاج الرماد: يتناوب طوراً جسديّاً وطور ظلّ، ويطفئ المنارات.</summary>
        AshCrown = 2,

        /// <summary>آكل الفجر: زعيم الحملة، ثلاثة أطوار، ويسحب نور الخريطة.</summary>
        EaterOfDawn = 3,
    }
}
