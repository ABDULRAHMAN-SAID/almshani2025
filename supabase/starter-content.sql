-- ---------------------------------------------------------------------------
-- بيانات التواصل — قيم مبدئية تُعدَّل من لوحة الإدارة ← التواصل
-- ---------------------------------------------------------------------------
update public.app_contact
set department = case when department = '' then 'قسم الأنشطة' else department end,
    hours      = case when hours = '' then 'الأحد – الخميس، 8 صباحًا – 2 ظهرًا' else hours end,
    office     = case when office = '' then 'مبنى الأنشطة' else office end,
    updated_at = now()
where id = 1;


-- ---------------------------------------------------------------------------
-- ما أُضيف
-- ---------------------------------------------------------------------------
select 'مقالات توعوية' as "البند", count(*) as "العدد" from public.awareness_articles
union all select 'أنشطة',        count(*) from public.activities
union all select 'إعلانات',      count(*) from public.announcements
union all select 'مجموعات',      count(*) from public.discussion_groups
union all select 'أسئلة مسابقة', count(*) from public.quiz_questions;
